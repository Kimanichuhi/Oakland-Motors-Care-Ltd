/*
# Oakland Motor Care physical stock register import

1. Purpose
- Adds Oakland's hand-counted stock register (spares counted on-site, with buying prices)
  to the parts catalogue as the real, current inventory.

2. Notes
- `quantity_on_hand` is populated from the register's physical "Total pieces" count.
- `cost_price_minor` is populated from the register's "Buying Price" (KES), stored as
  minor units. Where the register left buying price blank, cost_price_minor is 0 rather
  than a fabricated figure.
- `selling_price_minor` is left at 0 for every row: the register did not record retail
  prices for these items (one stray total in the source sheet was not a genuine
  per-unit selling price and was discarded rather than imported). Staff must set a
  selling price per part before these items are sellable.
- Where the register left "Part/spare No" blank, a synthetic SKU of the form
  `REG-<register count number>` is used so every row still has a stable, unique
  identifier traceable back to its row in the original register.
- Import is idempotent: a row is skipped if a part with the same SKU (case-insensitive)
  and a null branch_id already exists, so re-running this migration is safe.
*/

